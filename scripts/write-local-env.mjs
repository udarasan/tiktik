#!/usr/bin/env node
// Writes frontend/.env.local from the running local Supabase stack.
// Copies ONLY the API URL and the publishable key (CLAUDE.md rule 8).
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
let status;
try {
  status = JSON.parse(
    execFileSync('supabase', ['status', '-o', 'json', '--workdir', 'backend'], {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }),
  );
} catch {
  console.error(
    'Could not read `supabase status`. Start the stack first: cd backend && supabase start',
  );
  process.exit(1);
}

const url = status.API_URL;
const key = status.PUBLISHABLE_KEY;
if (!url || !key?.startsWith('sb_publishable_')) {
  console.error('`supabase status` did not return API_URL and a publishable key.');
  process.exit(1);
}

writeFileSync(
  new URL('../frontend/.env.local', import.meta.url),
  `# Generated by npm run env:local — local stack only, do not commit.\nVITE_SUPABASE_URL=${url}\nVITE_SUPABASE_PUBLISHABLE_KEY=${key}\n`,
);
console.log('Wrote frontend/.env.local');
